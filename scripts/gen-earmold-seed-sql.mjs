#!/usr/bin/env node
// Distil — regenerate the earmold_catalog seed migration from
// src/lib/earmoldSeed.js (the source of truth for the transcription).
// Writes idempotent upsert SQL to stdout; redirect into the seed migration:
//   node scripts/gen-earmold-seed-sql.mjs > supabase/migrations/<ts>_seed_earmold_catalog.sql

import { EARMOLD_SEED } from "../src/lib/earmoldSeed.js";

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

console.log(`/*!
 * Distil — hearing clinic patient management & intake system
 *
 * Copyright (c) 2026 Kurt Mooney. All rights reserved.
 * PROPRIETARY AND CONFIDENTIAL. See the LICENSE file at the repository root.
 */

-- Backlog #42 (phase a) — earmold_catalog seed, GENERATED by
-- scripts/gen-earmold-seed-sql.mjs from src/lib/earmoldSeed.js. Do not edit by
-- hand: edit the JS module and regenerate, keeping the two at parity
-- (insurancePlansSeed convention). Idempotent upsert so it can be re-run.
`);

for (const r of EARMOLD_SEED) {
  console.log(`insert into public.earmold_catalog
  (id, manufacturer, form_id, device_type, style_id, style_label, materials, vents, canal, tubing, extras, constraints_note, sort_order, confidence)
values (${q(r.id)}, ${q(r.manufacturer)}, ${q(r.formId)}, ${q(r.deviceType)}, ${q(r.styleId)}, ${q(r.styleLabel)}, ${j(r.materials)}, ${j(r.vents)}, ${j(r.canal)}, ${j(r.tubing)}, ${j(r.extras)}, ${q(r.constraintsNote)}, ${r.sortOrder}, ${q(r.confidence)})
on conflict (id) do update set
  manufacturer = excluded.manufacturer, form_id = excluded.form_id,
  device_type = excluded.device_type, style_id = excluded.style_id,
  style_label = excluded.style_label, materials = excluded.materials,
  vents = excluded.vents, canal = excluded.canal, tubing = excluded.tubing,
  extras = excluded.extras, constraints_note = excluded.constraints_note,
  sort_order = excluded.sort_order, confidence = excluded.confidence,
  updated_at = now();
`);
}
